#!/usr/bin/env python3
"""
Patch the android/ and ios/ folders generated by `flutter create` so the app can:
  * talk to the PC over plain HTTP on the local network
  * show the iOS "Local Network" permission prompt
  * use a friendly app name

Usage: python3 patch_platforms.py <path-to-flutter-project>
"""

import re
import sys
from pathlib import Path

root = Path(sys.argv[1] if len(sys.argv) > 1 else ".")
APP_NAME = "Shutdown Scheduler"


def patch_android():
    p = root / "android/app/src/main/AndroidManifest.xml"
    s = p.read_text(encoding="utf-8")
    if "android.permission.INTERNET" not in s:
        s = s.replace(
            "<application",
            '<uses-permission android:name="android.permission.INTERNET"/>\n    <application',
            1,
        )
    if "usesCleartextTraffic" not in s:
        s = s.replace("<application", '<application\n        android:usesCleartextTraffic="true"', 1)
    s = re.sub(r'android:label="[^"]*"', f'android:label="{APP_NAME}"', s, count=1)
    p.write_text(s, encoding="utf-8")
    print("patched", p)


def patch_ios():
    p = root / "ios/Runner/Info.plist"
    s = p.read_text(encoding="utf-8")
    if "NSLocalNetworkUsageDescription" not in s:
        add = (
            "\t<key>NSLocalNetworkUsageDescription</key>\n"
            "\t<string>Find and control your PC on your Wi-Fi network.</string>\n"
            "\t<key>NSAppTransportSecurity</key>\n"
            "\t<dict>\n"
            "\t\t<key>NSAllowsLocalNetworking</key>\n"
            "\t\t<true/>\n"
            "\t\t<key>NSAllowsArbitraryLoads</key>\n"
            "\t\t<true/>\n"
            "\t</dict>\n"
        )
        idx = s.rfind("</dict>")
        s = s[:idx] + add + s[idx:]
    s = re.sub(
        r"(<key>CFBundleDisplayName</key>\s*<string>)[^<]*(</string>)",
        rf"\g<1>{APP_NAME}\g<2>",
        s,
    )
    p.write_text(s, encoding="utf-8")
    print("patched", p)


if __name__ == "__main__":
    patch_android()
    patch_ios()
